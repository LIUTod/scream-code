/**
 * Builds the >1200-line table fixture: repeated blocks with unique entry
 * indices, fully deterministic across runs and processes.
 */
function buildBigTableContent(lineTarget: number): string {
  const lines: string[] = [
    '// Generated catalog table. Every block repeats with a unique index so the',
    '// benchmark fixtures stay deterministic across runs.',
    '',
  ];
  let entry = 0;
  while (lines.length < lineTarget) {
    entry += 1;
    lines.push(
      `// Catalog entry ${entry}.`,
      `const entry${entry} = { id: ${entry}, label: 'entry-${entry}', weight: ${entry} * 3, active: ${entry % 7 !== 0} };`,
      '',
      `export function priceFor${entry}(units: number): number {`,
      `  const base = entry${entry}.weight + units;`,
      `  if (units > entry${entry}.weight) return base + ${entry};`,
      `  return base - (${entry} % 4);`,
      '}',
      '',
    );
  }
  return lines.join('\n') + '\n';
}

